export function getPalettesForIndustry(industry: string, count: number = 100): Palette[] {
  const result: Palette[] = [];
  const totalPalettes = PALETTES.length;
  
  for (let i = 0; i < count; i++) {
    const randomIndex = Math.floor(Math.random() * totalPalettes);
    result.push(PALETTES[randomIndex]);
  }
  
  return result;
}

export function isDark(color: string): boolean {
  if (color.includes("linear-gradient")) {
    const match = color.match(/#[0-9A-F]{6}/i);
    if (match) color = match[0];
    else return false;
  }
  
  const hex = color.slice(1);
  const r = parseInt(hex.slice(0, 2), 16);
  const g = parseInt(hex.slice(2, 4), 16);
  const b = parseInt(hex.slice(4, 6), 16);
  
  return (r + g + b) / 3 < 128;
}